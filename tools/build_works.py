#!/usr/bin/env python3
"""Works(制作実績)ページの生成ツール。標準ライブラリだけで動きます(追加インストール不要)。

  python3 tools/build_works.py                 すべて生成(詳細ページ + 一覧)
  python3 tools/build_works.py --check         入力チェックだけ(ファイルは書き換えない)
  python3 tools/build_works.py --new <slug>    新しい案件フォルダと work.json の雛形を作る

案件の追加・修正は assets/works/<slug>/ の中だけ(work.json と画像)。
生成物 works/<番号>.html(例: works/009.html)と、works.html の「WORKS:LIST」の範囲は手で編集しない
(次回の生成で上書きされます)。詳しくは tools/README-works.md。
"""
import html
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORKS_DIR = ROOT / "assets" / "works"        # 案件フォルダ(データ+画像)
OUT_DIR = ROOT / "works"                      # 生成する詳細ページ(1案件1ページ)
TEMPLATE = ROOT / "tools" / "templates" / "works-detail.html"
ORDER_FILE = ROOT / "tools" / "works-order.txt"   # 表示順(1行1案件)
LIST_PAGE = ROOT / "works.html"

SITE_NAME = "株式会社Recologne"
NOINDEX = True        # 公開するときは False にして再生成(全詳細ページの noindex が外れる)
MORE_COUNT = 3        # 詳細ページ下部「More Works」に出す件数
ACCENTS = ["--teal", "--pink", "--orange", "--violet"]   # 指標カードの枠色(順番に使う)

GENERATED_MARK = "<!-- generated by tools/build_works.py : 手で編集しないでください (編集は assets/works/<slug>/work.json) -->"
LIST_START = "<!-- WORKS:LIST:START"
LIST_END = "<!-- WORKS:LIST:END -->"

DATE_RE = re.compile(r"^(\d{4})\.(\d{1,2})(?:\.(\d{1,2}))?$")   # 2025.1.31 または 2025.1
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
esc = lambda v: html.escape(str(v), quote=True)


# ---------------------------------------------------------------- 読み込み・検証
def image_size(path):
    """webp / png / jpeg の (幅, 高さ)。読めなければ None(レイアウトずれ防止の width/height 用)。"""
    try:
        d = path.read_bytes()
        if d[:8] == b"\x89PNG\r\n\x1a\n":
            return struct.unpack(">II", d[16:24])
        if d[:4] == b"RIFF" and d[8:12] == b"WEBP":
            k = d[12:16]
            if k == b"VP8X":
                return 1 + int.from_bytes(d[24:27], "little"), 1 + int.from_bytes(d[27:30], "little")
            if k == b"VP8 ":
                return struct.unpack("<H", d[26:28])[0] & 0x3FFF, struct.unpack("<H", d[28:30])[0] & 0x3FFF
            if k == b"VP8L":
                b = d[21:25]
                return 1 + (((b[1] & 0x3F) << 8) | b[0]), 1 + (((b[3] & 0xF) << 10) | (b[2] << 2) | ((b[1] & 0xC0) >> 6))
        if d[:2] == b"\xff\xd8":
            i = 2
            while i < len(d):
                if d[i] != 0xFF:
                    i += 1
                    continue
                m = d[i + 1]
                if 0xC0 <= m <= 0xCF and m not in (0xC4, 0xC8, 0xCC):
                    h, w = struct.unpack(">HH", d[i + 5:i + 9])
                    return w, h
                i += 2 + struct.unpack(">H", d[i + 2:i + 4])[0]
    except Exception:
        pass
    return None


def load_works():
    works, errors = [], []
    for d in sorted(WORKS_DIR.iterdir()):
        f = d / "work.json"
        if not (d.is_dir() and f.exists()):
            continue
        slug = d.name
        try:
            w = json.loads(f.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            errors.append(f"{slug}: work.json の書式エラー ({e})")
            continue
        e0 = len(errors)
        if not SLUG_RE.match(slug):
            errors.append(f"{slug}: フォルダ名は半角英小文字・数字・ハイフンのみ (例: 2025-01-brand-product)")
        for k in ("no", "date", "client", "promotion", "stats"):   # 画像・実施内容は後から入れてもよい(空なら準備中表示)
            if not w.get(k):
                errors.append(f"{slug}: work.json の「{k}」が未入力です")
        if w.get("no") and not (isinstance(w["no"], int) and not isinstance(w["no"], bool) and w["no"] >= 1):
            errors.append(f"{slug}: no は 1 以上の整数で入力してください (入力値: {w['no']})")
        m = DATE_RE.match(str(w.get("date", "")))
        if w.get("date") and not m:
            errors.append(f"{slug}: date は 2025.1.31 または 2025.1 の形式で入力してください (入力値: {w['date']})")
        for fn in [w.get("thumb")] + [i if isinstance(i, str) else i.get("file") for i in w.get("images", [])]:
            if fn and not (d / fn).exists():
                errors.append(f"{slug}: 画像ファイルがありません → assets/works/{slug}/{fn}")
        for i, s in enumerate(w.get("stats", [])):
            if not re.match(r"^\d+(\.\d+)?$", str(s.get("value", ""))) or not s.get("label"):
                errors.append(f"{slug}: stats[{i}] は label と、数字だけの value が必要です")
        if len(errors) == e0:
            w["slug"] = slug
            w["_sort"] = tuple(int(x) if x else 0 for x in m.groups())
            works.append(w)
    seen = {}
    for w in works:   # 番号の重複チェック(同じ番号だとページが上書きされるため)
        if w["no"] in seen:
            errors.append(f"番号 {w['no']} が重複しています: {seen[w['no']]} と {w['slug']}")
        seen[w["no"]] = w["slug"]
    # 並び順: tools/works-order.txt の順。書いていない案件は末尾に日付の新しい順
    order = []
    if ORDER_FILE.exists():
        for line in ORDER_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                order.append(line)
    known = {w["slug"] for w in works}
    for slug in order:
        if slug not in known:
            print(f"  [注意] works-order.txt に書かれた案件が見つかりません(無視します): {slug}")
    pos = {slug: i for i, slug in enumerate(order)}
    unlisted = sorted((w for w in works if w["slug"] not in pos), key=lambda w: (w["_sort"], w["no"]), reverse=True)
    for w in unlisted:
        print(f"  [注意] works-order.txt に未登録のため末尾に並べました: {w['slug']}")
    works = sorted((w for w in works if w["slug"] in pos), key=lambda w: pos[w["slug"]]) + unlisted
    return works, errors


def page_name(w):
    """詳細ページのファイル名。work.json の no を3桁にそろえる (no=9 → 009.html)"""
    return f"{w['no']:03d}.html"


# ---------------------------------------------------------------- 部品(HTML断片)
def title_of(w):
    """ページ・一覧に出す題名。work.json に title があればそれを優先、なければ「client　product」"""
    return w.get("title") or (w["client"] + ("　" + w["product"] if w.get("product") else ""))


def sub_of(w):
    """カード下段(商品・案件名)。product があればそれ、なければ title"""
    return w.get("product") or w.get("title") or ""


def fmt_stat(s):
    v = str(s["value"])
    dec = len(v.split(".")[1]) if "." in v else 0
    ip, _, fp = v.partition(".")
    return f"{int(ip):,}" + ("." + fp if fp else ""), dec


def stats_html(w):
    out = []
    for i, s in enumerate(w["stats"]):
        shown, dec = fmt_stat(s)
        label = esc(s["label"]) + ("　" + esc(s["label_ja"]) if s.get("label_ja") else "")
        value = (esc(s["prefix"]) + " " if s.get("prefix") else "")
        value += f'<span class="wd-count" data-count="{esc(s["value"])}" data-decimals="{dec}">{shown}</span>'
        value += esc(s.get("unit", ""))
        value += f'<span class="wd-stat-suffix">{esc(s["suffix"])}</span>' if s.get("suffix") else ""
        out.append(
            f'            <div class="wd-stat" style="--accent:var({ACCENTS[i % len(ACCENTS)]})">\n'
            f'              <div class="wd-stat-head"><span class="wd-stat-chip"></span><p class="wd-stat-label">{label}</p></div>\n'
            f'              <p class="wd-stat-value">{value}</p>\n'
            f"            </div>"
        )
    return "\n".join(out)


def tag_class(t):
    return "is-" + re.sub(r"[^a-z0-9]", "", t.lower())


def gallery_html(w, root):
    slug = w["slug"]
    imgs = [i if isinstance(i, dict) else {"file": i} for i in w["images"]]
    for i in imgs:
        i.setdefault("alt", f"{title_of(w)} の実績画像")
    if not imgs:   # 画像が未登録: 準備中の枠(画像を入れて再生成すれば自動で置き換わる)
        return '<figure class="wd-figure wd-figure--empty" id="wdv"><span>IMAGE COMING SOON</span></figure>'
    if len(imgs) == 1:   # 画像1枚: スクロール(カルーセル)にせず静止表示
        i = imgs[0]
        size = image_size(WORKS_DIR / slug / i["file"])
        wh = f' width="{size[0]}" height="{size[1]}"' if size else ""
        return (f'<figure class="wd-figure" id="wdv">'
                f'<img src="{root}assets/works/{slug}/{esc(i["file"])}" alt="{esc(i["alt"])}"{wh} decoding="async">'
                f"</figure>")
    items = [{"src": f"{root}assets/works/{slug}/{i['file']}", "t": i["alt"]} for i in imgs]
    return f'<div class="wdv" id="wdv" data-frame="none" data-items="{esc(json.dumps(items, ensure_ascii=False))}"></div>'


def rows_html(w):
    rows = [("Promotion", "プロモーション概要", "<br>".join(esc(l) for l in w["promotion"]))]
    if w.get("details"):
        rows.append(("Details", "実施内容", esc(w["details"])))
    if w.get("tags"):
        pills = "".join(f'\n                  <span class="wd-tag {tag_class(t)}">{esc(t)}</span>' for t in w["tags"])
        rows.append(("Tags", "媒体", None, pills))
    rows.append(("Client", "クライアント", esc(w.get("client_full") or w["client"])))
    if w.get("category"):
        rows.append(("Category", "カテゴリー", esc(w["category"])))
    if w.get("period"):
        rows.append(("Period", "実施期間", esc(w["period"])))
    out = []
    for r in rows:
        td = (f'<td class="wd-tags">{r[3]}\n                </td>' if r[2] is None else f"<td>{r[2]}</td>")
        out.append(f"              <tr>\n                <th>{r[0]}<br>{r[1]}</th>\n                {td}\n              </tr>")
    return "\n".join(out)


def more_cards_html(works, idx):
    # 「他の実績」は日付の新しい順(自分自身は除く)。同じ月の案件は、一覧(works-order.txt)の並びのまま
    others = sorted((w for i, w in enumerate(works) if i != idx), key=lambda w: w["_sort"], reverse=True)[:MORE_COUNT]
    out = []
    for n, o in enumerate(others, 1):
        tags = "".join(f"<span>{esc(t)}</span>" for t in o.get("tags", []))
        out.append(
            f'          <div class="wd-more-card" style="--i:{n}">\n'
            f'            <a class="wd-more-link-card" href="{page_name(o)}" data-view-cursor>\n'
            + (f'              <div class="wd-more-thumb"><img src="../assets/works/{o["slug"]}/{esc(o["thumb"])}" alt="" loading="lazy"></div>\n'
               if o.get("thumb") else '              <div class="wd-more-thumb wd-more-thumb--empty"><span>COMING SOON</span></div>\n')
            + f'              <div class="wd-more-body">\n'
            + (f'                <p class="wd-more-tags">{tags}</p>\n' if tags else "")
            + f'                <p class="wd-more-brand">{esc(o["client"])}</p>\n'
            + (f'                <p class="wd-more-brand-sub">{esc(sub_of(o))}</p>\n' if sub_of(o) else "")
            + "              </div>\n            </a>\n          </div>")
    return "\n".join(out)


def fill(tpl, values):
    def sub(m):
        k = m.group(1)
        if k not in values:
            raise KeyError(f"テンプレートに未対応の {{{{{k}}}}} があります")
        return values[k]
    return re.sub(r"\{\{([A-Z_]+)\}\}", sub, tpl)


# ---------------------------------------------------------------- 生成
def build_detail(w, works, idx, tpl):
    multi = len(w["images"]) > 1
    desc = f'Recologneのワークス詳細ページです。{title_of(w)}：' + " ".join(w["promotion"])
    desc = desc if len(desc) <= 150 else desc[:149] + "…"
    values = {
        "R": "../",
        "SITE_NAME": SITE_NAME,
        "TITLE": esc(title_of(w)),
        "DESCRIPTION": esc(desc),
        "ROBOTS": '<meta name="robots" content="noindex">' if NOINDEX else "",
        "DATE": esc(w["date"]),
        "CLIENT_FULL_LINE": f'\n            <p class="wd-client">{esc(w["client_full"])}</p>' if w.get("client_full") else "",
        "STATS": stats_html(w),
        "GALLERY": gallery_html(w, "../"),
        "DESC_BLOCK": f'<p class="wd-desc">{esc(w["description"])}</p>' if w.get("description") else "",
        "TABLE_ROWS": rows_html(w),
        "MORE_CARDS": more_cards_html(works, idx),
        "GALLERY_CSS": '<link rel="stylesheet" href="../assets/works-gallery.css">' if multi else "",
        "GALLERY_JS": '<script src="../assets/works-gallery.js"></script>' if multi else "",
    }
    page = fill(tpl, values)
    return page.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + GENERATED_MARK, 1)


def build_list_items(works):
    out = []
    for n, w in enumerate(works, 1):
        out.append(
            f'        <li class="work-item" style="--i:{n}">\n'
            f'          <a class="work-item-link" href="works/{page_name(w)}" data-view-cursor>\n'
            + (f'            <div class="work-item-thumb"><img src="assets/works/{w["slug"]}/{esc(w["thumb"])}" alt="" loading="lazy"></div>\n'
               if w.get("thumb") else '            <div class="work-item-thumb work-item-thumb--empty"><span>COMING SOON</span></div>\n')
            + f'            <div class="work-item-info">\n'
            f'              <p class="work-item-company">{esc(w["date"])}</p>\n'
            f'              <h2 class="work-item-title">{esc(title_of(w))}</h2>\n'
            f"            </div>\n          </a>\n        </li>")
    return "\n".join(out)


def write_if_changed(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def new_work(slug):
    if not SLUG_RE.match(slug):
        sys.exit("slug は半角英小文字・数字・ハイフンのみ (例: 2025-01-brand-product)")
    d = WORKS_DIR / slug
    if d.exists():
        sys.exit(f"すでにあります: {d}")
    used = []
    for f in WORKS_DIR.glob("*/work.json"):
        try:
            used.append(int(json.loads(f.read_text(encoding="utf-8")).get("no", 0)))
        except (ValueError, TypeError, json.JSONDecodeError):
            pass
    no = max(used, default=0) + 1   # 既存の最大番号+1(既存ページの番号・URLは変わらない)
    d.mkdir(parents=True)
    skeleton = {
        "no": no,
        "date": "2025.1.31",
        "client": "クライアント名",
        "product": "商品・案件名(なければ空文字 \"\")",
        "thumb": "thumb.webp",
        "images": ["01.webp"],
        "promotion": ["プロモーション概要(1行ずつ配列に分ける)"],
        "details": "実施内容(例: Instagramリール投稿、TikTok投稿)",
        "tags": ["TikTok", "Instagram"],
        "stats": [
            {"label": "Views", "label_ja": "再生回数", "value": "1000000", "suffix": "over"},
            {"label": "ENG%", "label_ja": "エンゲージメント率", "prefix": "AVG", "value": "5", "unit": "%"},
        ],
    }
    (d / "work.json").write_text(json.dumps(skeleton, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # 新しい案件は表示順の先頭に入れる(位置を変えたいときは works-order.txt の行を移動)
    if ORDER_FILE.exists():
        lines = ORDER_FILE.read_text(encoding="utf-8").splitlines()
        i = next((k for k, l in enumerate(lines) if l.strip() and not l.strip().startswith("#")), len(lines))
        lines.insert(i, slug)
        ORDER_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"作成しました: assets/works/{slug}/work.json (番号 {no} → 詳細ページは works/{no:03d}.html。表示順は先頭)\n"
          f"このフォルダに thumb.webp(一覧用サムネ)と 01.webp(詳細用画像)を入れて、work.json を書き換え、\n"
          f"python3 tools/build_works.py を実行してください。")


def main():
    args = sys.argv[1:]
    if args[:1] == ["--new"]:
        if len(args) != 2:
            sys.exit("使い方: python3 tools/build_works.py --new <slug>")
        return new_work(args[1])
    check_only = "--check" in args
    works, errors = load_works()
    if errors:
        print("入力エラー:\n  - " + "\n  - ".join(errors))
        sys.exit(1)
    if not works:
        sys.exit("案件がありません(assets/works/<slug>/work.json)")
    print(f"案件 {len(works)} 件を確認しました。")
    if check_only:
        return

    OUT_DIR.mkdir(exist_ok=True)
    tpl = TEMPLATE.read_text(encoding="utf-8")
    changed = 0
    for i, w in enumerate(works):
        changed += write_if_changed(OUT_DIR / page_name(w), build_detail(w, works, i, tpl))
    # 削除された案件・番号を変えた案件の古い生成ページを掃除(生成マーク付きのものだけ。手書きページは触らない)
    names = {page_name(w) for w in works}
    for f in OUT_DIR.glob("*.html"):
        if f.name not in names and GENERATED_MARK in f.read_text(encoding="utf-8"):
            f.unlink()
            print(f"  古い生成ページを削除: works/{f.name}")

    page = LIST_PAGE.read_text(encoding="utf-8")
    a, b = page.find(LIST_START), page.find(LIST_END)
    if a < 0 or b < 0:
        sys.exit("works.html に WORKS:LIST:START / END のマーカーがありません")
    head_end = page.index("-->", a) + 3
    new_page = page[:head_end] + "\n" + build_list_items(works) + "\n        " + page[b:]
    changed += write_if_changed(LIST_PAGE, new_page)
    print(f"生成しました: works/*.html {len(works)} 件 + works.html(変更 {changed} ファイル)")


if __name__ == "__main__":
    main()
